test("revalidates unique paths and reports per-path errors", async () => {
  const revalidated = [];
  const warmed = [];
  const body = JSON.stringify({
    paths: ["/", "/work/", "/work", "/bad#hash", "/fails"],
  });
  const response = await handleCloakWpRequest(
    new Request("https://site.test/api/cloakwp/revalidate", {
      method: "POST",
      headers: { Authorization: `Bearer ${secret}` },
      body,
    }),
    requestOptions({
      revalidatePath(path) {
        if (path === "/fails") throw new Error("cache unavailable");
        revalidated.push(path);
      },
      scheduleCacheWarming(paths) {
        warmed.push(...paths);
      },
    }),
  );

  assert.equal(response.status, 207);
  assert.deepEqual(revalidated, ["/", "/work"]);
  assert.deepEqual(warmed, ["/", "/work"]);
});

